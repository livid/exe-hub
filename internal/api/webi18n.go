// rxName is an emoji's name in this language, as Unicode's CLDR gives
// it; the emoji itself for no emoji.
func (l *webLocale) rxName(e string) string {
	if n := emoji.Name(l.Code, e); n != "" {
		return n
	}
	return e
}

// rxTable is the picker's own 24, each with its name in this language.
func (l *webLocale) rxTable() [][2]string {
	out := make([][2]string, len(rxQuick))
	for i, e := range rxQuick {
		out[i] = [2]string{e, l.rxName(e)}
	}
	return out
}

// rxNames is where the picker's search reads every emoji's name: this
// language's table, then English's, which a search matches too (one
// address on an English page). Each carries its table's version, so a
// browser keeps it for good.
func (l *webLocale) rxNames() []string {
	var out []string
	for _, lang := range []string{l.Code, "en"} {
		if _, ver := emoji.Names(lang); ver != "" && !slices.Contains(out, "/v1/emoji/"+lang+"?v="+ver) {
			out = append(out, "/v1/emoji/"+lang+"?v="+ver)
		}
	}
	return out
}

func isOne(v any) bool {
	switch n := v.(type) {
	case int:
		return n == 1
	case int64:
		return n == 1
	case int32:
		return n == 1
	}
	return false
}

// webTmpls is the page template, parsed once for each language with T
// bound to it and build naming the build that serves it (offline.go);
// the stats desk's blocks come from the package that draws it (its own
// words are still English), parsed into each set so the desk renders
// inside the hub's chrome.
var webTmpls = func() map[string]*template.Template {
	out := map[string]*template.Template{}
	for code, l := range webLocales {
		t := template.New("web").Funcs(stats.Funcs()).Funcs(template.FuncMap{"T": l.T, "build": func() string { return webBuild },
			"rxname": l.rxName, "words": func(ids []string) string { return strings.Join(ids, " ") }})
		out[code] = template.Must(template.Must(t.Parse(webHTML)).Parse(stats.TemplateHTML()))
	}
	return out
}()

